"""(Needs the single sprite files: run tools/fetch_data.py first, it downloads them into sprites/.)
Packs every sprite in sprites/ into a few sheets (sprites/atlas/sheet-N.webp, lossless) plus data/atlas.js, so a page needs a handful of requests instead of hundreds.
Run again after adding sprites:  python tools/build_atlas.py"""
import os, json, re
from PIL import Image

CELL, COLS, ROWS = 96, 12, 12
src = 'sprites'
ids = sorted(int(f[:-4]) for f in os.listdir(src) if re.fullmatch(r'\d+\.png', f))
os.makedirs(os.path.join(src, 'atlas'), exist_ok=True)
for f in os.listdir(os.path.join(src, 'atlas')):
    os.remove(os.path.join(src, 'atlas', f))
per = COLS * ROWS
m = {}
sheets = []
for s in range(0, len(ids), per):
    chunk = ids[s:s + per]
    sheet = Image.new('RGBA', (COLS * CELL, ROWS * CELL), (0, 0, 0, 0))
    for k, i in enumerate(chunk):
        im = Image.open(os.path.join(src, f'{i}.png')).convert('RGBA')
        if im.width > CELL or im.height > CELL:
            im.thumbnail((CELL, CELL), Image.NEAREST)
        col, row = k % COLS, k // COLS
        sheet.paste(im, (col * CELL + (CELL - im.width) // 2, row * CELL + (CELL - im.height) // 2))
        bb = im.getchannel('A').point(lambda a: 255 if a > 20 else 0).getbbox() or (0, 0, im.width, im.height)
        ox, oy = (CELL - im.width) // 2, (CELL - im.height) // 2
        m[i] = [len(sheets), col, row, bb[0] + ox, bb[1] + oy, bb[2] + ox, bb[3] + oy]      # sheet, cell, then the visible box inside the cell
    name = f'sprites/atlas/sheet-{len(sheets)}.webp'
    sheet.save(name, 'WEBP', lossless=True, quality=100, method=6)
    sheets.append(name)
    print(name, os.path.getsize(name) // 1024, 'KB')
with open('data/atlas.js', 'w') as f:
    f.write('// generated by tools/build_atlas.py\nwindow.PB = window.PB || {};\nPB.ATLAS = ' + json.dumps({'cell': CELL, 'cols': COLS, 'rows': ROWS, 'sheets': sheets, 'map': {str(k): v for k, v in m.items()}}, separators=(',', ':')) + ';\n')
print(len(ids), 'sprites,', sum(os.path.getsize(s) for s in sheets) // 1024, 'KB total')
